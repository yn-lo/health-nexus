"""
服务接口契约定义

基于 SOLID 原则设计的接口层：
- ISP: 每个接口只包含单一职责的方法，客户端不被迫依赖不需要的接口
- LSP: 接口使用 Django Model 类型而非 Stub，确保实现可安全替换
- DIP: 高层模块依赖这些抽象接口，而非具体实现
"""

from typing import Protocol, List, Dict, Optional, Tuple, Any, TYPE_CHECKING

