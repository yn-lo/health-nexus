class IDepartmentService(Protocol):
    def get_public_departments(self) -> List['Department']: ...
    def get_user_departments(self, user) -> List['Department']: ...
    def get_all_departments(self, exclude_public: bool = False) -> List['Department']: ...
    def get_department_by_id(self, dept_id: int) -> Optional['Department']: ...
    def create_department(self, data: Dict, user=None) -> 'Department': ...
    def update_department(self, dept_id: int, data: Dict, user=None) -> 'Department': ...
    def delete_department(self, dept_id: int, user=None) -> bool: ...
    def get_department_tree(self) -> List[Dict]: ...
    def add_member(self, dept_id: int, user_id: int, role: str, is_primary: bool = False, actor=None) -> Any: ...
    def remove_member(self, dept_id: int, user_id: int, actor=None) -> bool: ...
    def get_members(self, dept_id: int) -> List[Dict]: ...


